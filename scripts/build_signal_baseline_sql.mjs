// Writes the migration that loads the Community Signal's public-forum baseline
// from shared/signal_baseline.json (the same file the preview uses).
// Usage: node scripts/build_signal_baseline_sql.mjs          (write the migration)
//        node scripts/build_signal_baseline_sql.mjs --check  (fail if it is out of date)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const target = new URL('supabase/migrations/20261022000200_signal_baseline.sql', root);
const { compounds } = JSON.parse(readFileSync(new URL('shared/signal_baseline.json', root), 'utf8'));

const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${(a || []).map(q).join(', ')}]::text[]`;
const int = (n) => {
  if (!Number.isInteger(n) || n < 0 || n > 100) throw new Error(`bad component ${n}`);
  return String(n);
};
const rows = compounds.map((c) => `  (${[
  q(c.compound_id), int(c.efficacy), int(c.consistency), int(c.diversity), int(c.confidence),
  `${q(JSON.stringify(c.themes || []))}::jsonb`, arr(c.source_families), q(c.volume_label),
].join(', ')})`);

const sql = `-- Generated by scripts/build_signal_baseline_sql.mjs from shared/signal_baseline.json.
-- Don't edit by hand: change the JSON, rerun the script, and commit both.
--
-- The starting Community Signal for ${compounds.length} compounds, from public forums. As first-hand
-- reports here add up, they take over (see private.signal_compute).

insert into public.signal_baseline
  (compound_id, efficacy, consistency, diversity, confidence, themes, source_families, volume_label)
values
${rows.join(',\n')}
on conflict (compound_id) do update
  set efficacy = excluded.efficacy, consistency = excluded.consistency, diversity = excluded.diversity,
      confidence = excluded.confidence, themes = excluded.themes, source_families = excluded.source_families,
      volume_label = excluded.volume_label, updated_at = now();

-- The first snapshot for each compound
select private.signal_compute(compound_id) from public.signal_baseline order by compound_id;
`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== sql) {
    console.error('The Signal baseline migration is out of date. Run: node scripts/build_signal_baseline_sql.mjs');
    process.exit(1);
  }
  console.log(`Signal baseline migration matches shared/signal_baseline.json (${compounds.length} compounds)`);
} else {
  writeFileSync(target, sql);
  console.log(`wrote ${target.pathname} (${compounds.length} compounds)`);
}
